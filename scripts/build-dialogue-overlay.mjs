import {readFileSync,writeFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
// Existing pure UMD modules run against a private namespace. Consumers only
// receive JinmenDialogue; their own globals and styles remain untouched.
const files=['caption-layout.js','stage-layout.js','dialogue-overlay.js'];
const source=files.map(f=>readFileSync(new URL(f,root),'utf8')).join('\n');
writeFileSync(new URL('integration/dialogue-overlay.bundle.js',root),`/* Generated by scripts/build-dialogue-overlay.mjs. Do not edit. */\n(function(host){\n'use strict';\nconst api=(function(){const globalThis={},module=undefined;\n${source}\nreturn globalThis.DialogueOverlay;})();\nhost.JinmenDialogue=api;\n})(globalThis);\n`);
